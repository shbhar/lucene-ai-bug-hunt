  /** fromDISI itself, through a subclass (it is protected static). */
  public void testFromDISIAdvanceUpdatesIndex() throws IOException {
    FixedBitSet docs = new FixedBitSet(10);
    docs.set(1);
    docs.set(3);
    docs.set(5);
    docs.set(7);
    KnnVectorValues.DocIndexIterator it = FromDisi.of(new BitSetIterator(docs, 4));
    assertEquals(5, it.advance(5));
    assertEquals("ordinal of doc 5 (docs 1,3,5,7 have ordinals 0..3)", 2, it.index());
  }

  /** The index-level contract, on the 9.4.2 index: advance(doc) then vectorValue(index()). */
  public void testLucene94SparseByteVectorsAdvance() throws IOException {
    Path path = createTempDir("sparse-byte-94");
    TestUtil.unzip(new ByteArrayInputStream(Base64.getDecoder().decode(INDEX_ZIP_BASE64)), path);
    try (Directory dir = newFSDirectory(path);
        DirectoryReader reader = DirectoryReader.open(dir)) {
      assertEquals(1, reader.leaves().size());
      LeafReader leaf = reader.leaves().get(0).reader();
      StoredFields stored = leaf.storedFields();
      ByteVectorValues values = leaf.getByteVectorValues("v");
      KnnVectorValues.DocIndexIterator it = values.iterator();
      // position on doc 2 directly, as a function query or rescorer does for its first hit
      assertEquals(2, it.advance(2));
      BytesRef expected = stored.document(2).getBinaryValue("expected");
      assertArrayEquals(
          "vector of doc 2 read through advance()/index()",
          BytesRef.deepCopyOf(expected).bytes,
          values.vectorValue(it.index()));
    }
  }

  /** The same through a public function-query value source. */
  public void testByteKnnVectorFieldSourceOnLucene94SparseField() throws IOException {
    Path path = createTempDir("sparse-byte-94-vs");
    TestUtil.unzip(new ByteArrayInputStream(Base64.getDecoder().decode(INDEX_ZIP_BASE64)), path);
    try (Directory dir = newFSDirectory(path);
        DirectoryReader reader = DirectoryReader.open(dir)) {
      LeafReaderContext ctx = reader.leaves().get(0);
      StoredFields stored = ctx.reader().storedFields();
      FunctionValues fv = new ByteKnnVectorFieldSource("v").getValues(new HashMap<>(), ctx);
      StringBuilder mismatches = new StringBuilder();
      for (int doc = 0; doc < ctx.reader().maxDoc(); doc += 2) { // the docs with a vector, in order
        byte[] want = BytesRef.deepCopyOf(stored.document(doc).getBinaryValue("expected")).bytes;
        byte[] got;
        try {
          got = fv.byteVectorVal(doc);
        } catch (RuntimeException | IOException e) {
          mismatches.append(" doc ").append(doc).append(": threw ").append(e);
          continue;
        }
        if (Arrays.equals(want, got) == false) {
          mismatches
              .append(" doc ")
              .append(doc)
              .append(": expected ")
              .append(Arrays.toString(want))
              .append(" got ")
              .append(Arrays.toString(got));
        }
      }
      assertEquals(
          "ByteKnnVectorFieldSource values that differ from the indexed vectors:",
          "",
          mismatches.toString());
    }
  }

  /** gives the test access to the protected static helper */
  private abstract static class FromDisi extends ByteVectorValues {
    static DocIndexIterator of(org.apache.lucene.search.DocIdSetIterator disi) {
      return fromDISI(disi);
    }
  }
